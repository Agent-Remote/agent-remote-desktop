# Run the same runtime-only probes as native-acceptance.sh from PowerShell.
#
# This wrapper is intended for Windows hosts that do not have Git Bash. It
# never sets GOOS/GOARCH and records the host selected by Go's GOHOST* values.
# A release build or cross-build is not runtime evidence.
[CmdletBinding()]
param(
    [string]$EvidenceDir = "",
    [switch]$SkipWorkbench,
    [string]$WireGuardCliBinary = "",
    [ValidateSet("", "darwin", "windows", "linux")]
    [string]$Target = ""
)

$ErrorActionPreference = "Stop"
$RootDir = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
if ([string]::IsNullOrWhiteSpace($EvidenceDir)) {
    $EvidenceDir = Join-Path ([IO.Path]::GetTempPath()) "agent-remote-desktop-native-acceptance"
}
New-Item -ItemType Directory -Force -Path $EvidenceDir | Out-Null
# Evidence directories are commonly reused for retries. Remove only files
# generated by this wrapper so a previous successful broker/log result cannot
# be combined with the current run (for example when WireGuard is omitted).
foreach ($name in @("summary.txt", "metadata.txt", "platform.log", "installer.log", "native-window.log", "tray.log", "workbench.log", "wireguard.log", "wireguard-broker.log", "target-preflight.log", "failure.log")) {
    $path = Join-Path $EvidenceDir $name
    if (Test-Path -LiteralPath $path) { Remove-Item -Force -LiteralPath $path }
}
$wireguardEvidence = Join-Path $EvidenceDir "wireguard"
if (Test-Path -LiteralPath $wireguardEvidence) { Remove-Item -Recurse -Force -LiteralPath $wireguardEvidence }
Set-Location $RootDir

$goos = "unknown"
$goarch = "unknown"
$currentStep = "initialization"
$status = "running"
$exitCode = 0

function Write-Summary {
    param([int]$Code)
    if ($script:status -eq "running") {
        $script:status = if ($Code -eq 0) { "passed" } else { "failed" }
        $script:exitCode = $Code
    }
    @(
        "status=$($script:status)"
        "exit_code=$($script:exitCode)"
        "failed_step=$($script:currentStep)"
        "runtime=$($script:goos)/$($script:goarch)"
        "cross_compilation=false"
        "evidence=$EvidenceDir"
    ) | Set-Content -Encoding utf8 (Join-Path $EvidenceDir "summary.txt")
}

try {
    # GOOS/GOARCH select a build target. GOHOSTOS/GOHOSTARCH identify the
    # machine executing this script even when a cross-build shell exported the
    # selectors. Remove them before invoking each probe.
    $goos = (& go env GOHOSTOS).Trim()
    $goarch = (& go env GOHOSTARCH).Trim()
    if (-not [string]::IsNullOrWhiteSpace($Target) -and $Target -ne $goos) {
        $currentStep = "target-preflight"
        $exitCode = 3
        "target=$Target`nactual_host=$goos`nstatus=not_run`nreason=target host is unavailable; native acceptance never cross-runs" | Set-Content -Encoding utf8 (Join-Path $EvidenceDir "target-preflight.log")
        $status = "not_run"
        throw "target host $Target is unavailable on $goos"
    }
    if ($goos -ne "windows" -or @("amd64", "arm64") -notcontains $goarch) {
        throw "native-acceptance: unsupported host $goos/$goarch (FreeBSD is not a release target)"
    }
    $revision = "unknown"
    try { $revision = (& git rev-parse --short HEAD 2>$null).Trim() } catch {}
    $mygoVersion = "unknown"
    try {
        $candidate = (& go list -m -f '{{.Version}}' github.com/egoist/mygo 2>$null).Trim()
        if (-not [string]::IsNullOrWhiteSpace($candidate)) { $mygoVersion = $candidate }
    } catch {}
    $sessionName = if ([string]::IsNullOrWhiteSpace($env:SESSIONNAME)) { "unknown" } else { $env:SESSIONNAME }
    @(
        "recorded_at_utc=$([DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ'))"
        "runtime_goos=$goos"
        "runtime_goarch=$goarch"
        "go_version=$((& go version).Trim())"
        "mygo_version=$mygoVersion"
        "revision=$revision"
        "display=windows-native"
        "desktop_session=$sessionName"
        "ui_display=host"
        "display_protocol=win32"
    ) | Set-Content -Encoding utf8 (Join-Path $EvidenceDir "metadata.txt")

    function Invoke-Probe {
        param(
            [string]$Name,
            [string[]]$Arguments,
            [hashtable]$Environment = @{}
        )
        $script:currentStep = $Name
        $log = Join-Path $EvidenceDir "$Name.log"
        "== $Name ==" | Set-Content -Encoding utf8 $log
        "command: go $($Arguments -join ' ')" | Add-Content -Encoding utf8 $log
        $saved = @{}
        foreach ($key in @("GOOS", "GOARCH", "DESKTOP_NATIVE_ACCEPTANCE", "DESKTOP_TERMINAL_TESTS")) {
            $saved[$key] = [Environment]::GetEnvironmentVariable($key, "Process")
            [Environment]::SetEnvironmentVariable($key, $null, "Process")
        }
        foreach ($pair in $Environment.GetEnumerator()) {
            [Environment]::SetEnvironmentVariable($pair.Key, [string]$pair.Value, "Process")
        }
        try {
            & go @Arguments 2>&1 | Tee-Object -FilePath $log -Append
            # Capture the native command's status before any PowerShell
            # cleanup or logging can overwrite $LASTEXITCODE. The summary is
            # consumed as release evidence, so retaining the real probe code
            # makes a failed Windows run diagnosable and fail-closed.
            $probeExitCode = [int]$LASTEXITCODE
            if ($probeExitCode -ne 0) {
                $script:exitCode = $probeExitCode
                throw "probe exited with code $probeExitCode"
            }
        } finally {
            foreach ($key in $saved.Keys) {
                [Environment]::SetEnvironmentVariable($key, $saved[$key], "Process")
            }
        }
    }

    Invoke-Probe -Name "platform" -Arguments @("run", "./tests/platform-probe") -Environment @{ DESKTOP_NATIVE_ACCEPTANCE = "1" }
    Invoke-Probe -Name "installer" -Arguments @("run", "./tests/installer-probe") -Environment @{ DESKTOP_NATIVE_ACCEPTANCE = "1" }
    Invoke-Probe -Name "native-window" -Arguments @("run", "./tests/native-probe") -Environment @{ DESKTOP_TERMINAL_TESTS = "1" }
    Invoke-Probe -Name "tray" -Arguments @("run", "./tests/tray-probe") -Environment @{ DESKTOP_NATIVE_ACCEPTANCE = "1" }
    if ($SkipWorkbench) {
        $currentStep = "workbench"
        "workbench=skipped (SkipWorkbench)" | Set-Content -Encoding utf8 (Join-Path $EvidenceDir "workbench.log")
    } else {
        Invoke-Probe -Name "workbench" -Arguments @("run", "./tests/workbench-probe") -Environment @{ DESKTOP_TERMINAL_TESTS = "1" }
    }
    if ([string]::IsNullOrWhiteSpace($WireGuardCliBinary)) {
        "status=not_run`nreason=WireGuardCliBinary was not provided; no broker evidence was claimed" | Set-Content -Encoding utf8 (Join-Path $EvidenceDir "wireguard.log")
    } else {
        $wireguardDir = Join-Path $EvidenceDir "wireguard"
        New-Item -ItemType Directory -Force -Path $wireguardDir | Out-Null
        $cliScript = Join-Path $RootDir "..\agent-remote-cli\scripts\native-wireguard-broker-acceptance.ps1"
        if (-not (Test-Path -LiteralPath $cliScript -PathType Leaf)) { throw "missing WireGuard broker acceptance script: $cliScript" }
        $currentStep = "wireguard-broker"
        & $cliScript -CliBinary $WireGuardCliBinary -EvidenceDir $wireguardDir 2>&1 | Tee-Object -FilePath (Join-Path $EvidenceDir "wireguard-broker.log")
        if ($LASTEXITCODE -ne 0) { throw "WireGuard broker acceptance exited with code $LASTEXITCODE" }
    }
    $status = "passed"
    $exitCode = 0
} catch {
    if ($script:exitCode -le 0) { $script:exitCode = 1 }
    $exitCode = $script:exitCode
    "native-acceptance: $($_.Exception.Message)" | Add-Content -Encoding utf8 (Join-Path $EvidenceDir "failure.log")
    if ($script:status -eq "running") { $status = "failed" }
} finally {
    Write-Summary $exitCode
}

Get-Content (Join-Path $EvidenceDir "summary.txt")
if ($exitCode -ne 0) { exit $exitCode }
